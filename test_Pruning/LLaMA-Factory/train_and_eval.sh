#!/bin/bash

# ==============================================================================
#           自动化工作流 (纯顺序执行器版)
# ==============================================================================
#
# 工作模式:
# 1. 训练脚本 `train_pat.sh` 将模型保存到一个预定义的、固定的路径。
# 2. 评估脚本 `run_evaluation.sh` 从同一个预定义的路径加载模型。
# 3. 本脚本仅负责按顺序触发这两个过程，不传递任何路径信息。
#
# ==============================================================================

# --- 配置区 ---
TRAIN_ENV_NAME="test-pat"
EVAL_ENV_NAME="opencompass-pat"

# --- 脚本核心逻辑 (无需修改) ---

# 设置脚本在遇到错误时立即退出
set -e
set -o pipefail

echo "=============================================================================="
echo "🚀 步骤 1/2: 在 Conda 环境 '${TRAIN_ENV_NAME}' 中执行训练..."
echo "=============================================================================="

conda run -n "${TRAIN_ENV_NAME}" bash ./train_pat.sh

echo "✅ 训练脚本执行完成。"

echo "=============================================================================="
echo "📊 步骤 2/2: 在 Conda 环境 '${EVAL_ENV_NAME}' 中执行评估..."
echo "=============================================================================="

conda run -n "${EVAL_ENV_NAME}" bash ./run_evaluation.sh

if [ $? -eq 0 ]; then
    echo "🎉 评估脚本执行完成。"
else
    # `set -e` 理论上会处理，但这里为了日志清晰
    echo "❌ 错误: 评估脚本执行失败！"
    exit 1
fi

echo "=============================================================================="
echo "✨ 全部流程成功结束！✨"
echo "=============================================================================="